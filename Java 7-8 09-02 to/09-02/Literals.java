class Literals {

       public static void main(String[] args) {
              // The following are int literals
              int a = 10;
              // long literal
              long b = 20L;

               // other number literals
               // binary literal
               int c = 0b101;
	System.out.println(c);
                // octal literal
                int d = 027;
	System.out.println(d);
                // hexa decimal
                int e = 0x1e;
	System.out.println(e);

                 // unicode system
                 System.out.println("\u0041");  // A
       }

}